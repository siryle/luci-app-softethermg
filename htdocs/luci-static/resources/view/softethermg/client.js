'use strict';
'require baseclass';

// SoftEther uses SHA-0, whose message schedule differs from SHA-1.
function passwordHash(password, username) {
	const input = new TextEncoder().encode(password + username.toUpperCase());
	const data = new Uint8Array(Math.ceil((input.length + 9) / 64) * 64);
	data.set(input);
	data[input.length] = 0x80;
	const words = new DataView(data.buffer);
	words.setUint32(data.length - 8, Math.floor(input.length / 0x20000000));
	words.setUint32(data.length - 4, input.length * 8);
	const hash = [0x67452301, 0xefcdab89, 0x98badcfe, 0x10325476, 0xc3d2e1f0];
	const rotate = (word, bits) => (word << bits) | (word >>> (32 - bits));
	for (let offset = 0; offset < data.length; offset += 64) {
		const w = new Int32Array(80);
		for (let i = 0; i < 16; i++) w[i] = words.getInt32(offset + i * 4);
		for (let i = 16; i < 80; i++) w[i] = w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16];
		let [a, b, c, d, e] = hash;
		for (let i = 0; i < 80; i++) {
			const f = i < 20 ? ((b & c) | (~b & d)) : i < 40 ? (b ^ c ^ d) : i < 60 ? ((b & c) | (b & d) | (c & d)) : (b ^ c ^ d);
			const k = i < 20 ? 0x5a827999 : i < 40 ? 0x6ed9eba1 : i < 60 ? 0x8f1bbcdc : 0xca62c1d6;
			const next = (rotate(a, 5) + f + e + k + w[i]) | 0;
			[a, b, c, d, e] = [next, a, rotate(b, 30), c, d];
		}
		[a, b, c, d, e].forEach((value, i) => { hash[i] = (hash[i] + value) | 0; });
	}
	const output = new Uint8Array(20);
	const result = new DataView(output.buffer);
	hash.forEach((value, i) => result.setInt32(i * 4, value));
	return btoa(String.fromCharCode(...output));
}

function escapeValue(value) {
	return String(value).replace(/[\x00-\x20$]/g, ch => '$' + ch.charCodeAt(0).toString(16).toUpperCase().padStart(2, '0')) || '$';
}

function buildFile(options) {
	const { host, hub, username, password = '', accountName = '', authType = 1 } = options;
	const port = Number(options.port);
	if (!host || /[\s\x00-\x1f\x7f/\\?#@]/.test(host) || host.includes('://'))
		throw new Error(_('请输入服务端域名或 IP 地址，不包含协议、端口或路径。'));
	try { new URL(host.includes(':') ? `http://[${host}]/` : `http://${host}/`); }
	catch (_) { throw new Error(_('请输入有效的服务端域名或 IP 地址。')); }
	if (!Number.isInteger(port) || port < 1 || port > 65535)
		throw new Error(_('端口必须是 1–65535 范围内的整数。'));
	if (!hub || !username || ![0, 1, 2, 3, 4, 5].includes(authType))
		throw new Error(_('用户或认证类型无效，请刷新用户列表。'));

	const clientAuth = { 0: 0, 1: 1, 2: 3, 3: 3, 4: 2, 5: 2 }[authType];
	if (password && ![1, 4, 5].includes(authType))
		throw new Error(_('此认证方式不支持在文件中嵌入密码。'));
	const auth = [
		['uint', 'AuthType', clientAuth],
		['byte', 'HashedPassword', password && authType === 1 ? passwordHash(password, username) : ''],
		['string', 'PlainPassword', password && [4, 5].includes(authType) ? password : ''],
		['string', 'Username', username]
	];
	const client = [
		['string', 'AccountName', accountName || `${hub} - ${username}`],
		['uint', 'AdditionalConnectionInterval', 1], ['uint', 'ConnectionDisconnectSpan', 0],
		['string', 'CustomHttpHeader', ''], ['string', 'DeviceName', 'VPN'],
		['bool', 'DisableQoS', false], ['bool', 'HalfConnection', false],
		['bool', 'HideNicInfoWindow', false], ['bool', 'HideStatusWindow', false],
		['string', 'Hostname', host], ['string', 'HubName', hub],
		['uint', 'MaxConnection', 1], ['bool', 'NoRoutingTracking', false],
		['bool', 'NoTls1', false], ['bool', 'NoUdpAcceleration', false],
		['uint', 'NumRetry', 4294967295], ['uint', 'Port', port], ['uint', 'PortUDP', 0],
		['string', 'ProxyName', ''], ['byte', 'ProxyPassword', ''], ['uint', 'ProxyPort', 0],
		['uint', 'ProxyType', 0], ['string', 'ProxyUsername', ''],
		['bool', 'RequireBridgeRoutingMode', false], ['bool', 'RequireMonitorMode', false],
		['uint', 'RetryInterval', 15], ['bool', 'UseCompress', false], ['bool', 'UseEncrypt', true]
	];
	const root = [
		['bool', 'CheckServerCert', false], ['uint64', 'CreateDateTime', 0],
		['uint64', 'LastConnectDateTime', 0], ['bool', 'StartupAccount', false], ['uint64', 'UpdateDateTime', 0]
	];
	const lines = ['# VPN Client VPN Connection Setting File', '# Generated by LuCI SoftEther VPN Manager', '', 'declare root', '{'];
	const add = (entries, indent) => entries.forEach(([type, key, value]) => lines.push(`${indent}${type} ${key} ${typeof value === 'string' ? escapeValue(value) : value}`));
	add(root, '\t');
	for (const [name, entries] of [['ClientAuth', auth], ['ClientOption', client]]) {
		lines.push(`\tdeclare ${name}`, '\t{');
		add(entries, '\t\t');
		lines.push('\t}');
	}
	lines.push('}', '');
	const filename = `${hub}-${username}`.replace(/[^\p{L}\p{N}._-]/gu, '_').replace(/^[._]+|[._]+$/g, '') || 'connection';
	return { filename: /\.vpn$/i.test(filename) ? filename : filename + '.vpn', content: '\ufeff' + lines.join('\r\n') };
}

return baseclass.extend({ buildFile, passwordHash, escapeValue });

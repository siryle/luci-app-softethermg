#!/bin/bash
set -euo pipefail

VERSION="${1:-1.0.0}"
RELEASE="1"
PKG_NAME="luci-app-softethermg"
DIST_DIR="${PWD}/release-assets"

mkdir -p "$DIST_DIR"

echo "==> Building ${PKG_NAME} version ${VERSION}-${RELEASE}..."

# 1. Run in Alpine to build modern OpenWrt APK package
if command -v docker >/dev/null 2>&1; then
	echo "==> Building modern APK package via Docker (Alpine)..."
	docker run --rm -v "${PWD}:/work" -w /work alpine:edge sh -c "
		apk add --no-cache apk-tools tar gzip

		STAGING_DIR=\$(mktemp -d)
		mkdir -p \"\$STAGING_DIR/etc/config\"
		mkdir -p \"\$STAGING_DIR/etc/init.d\"
		mkdir -p \"\$STAGING_DIR/etc/uci-defaults\"
		mkdir -p \"\$STAGING_DIR/usr/libexec/rpcd\"
		mkdir -p \"\$STAGING_DIR/usr/share/luci/menu.d\"
		mkdir -p \"\$STAGING_DIR/usr/share/rpcd/acl.d\"
		mkdir -p \"\$STAGING_DIR/usr/share/softethermg\"
		mkdir -p \"\$STAGING_DIR/www/luci-static/resources/view/softethermg\"

		cp -r root/etc/* \"\$STAGING_DIR/etc/\"
		cp -r root/usr/* \"\$STAGING_DIR/usr/\"
		cp -r htdocs/luci-static/resources/view/softethermg/* \"\$STAGING_DIR/www/luci-static/resources/view/softethermg/\"

		chmod +x \"\$STAGING_DIR/etc/init.d/softethermg\"
		chmod +x \"\$STAGING_DIR/usr/share/softethermg/api.sh\"
		chmod +x \"\$STAGING_DIR/usr/libexec/rpcd/luci.softethermg\"

		# Generate modern OpenWrt APKv3 package
		apk mkpkg \
			--info name:${PKG_NAME} \
			--info version:${VERSION}-r${RELEASE} \
			--info arch:all \
			--info description:\"LuCI support for SoftEther VPN Server Manager\" \
			--info url:\"https://github.com/siryle/luci-app-softethermg\" \
			--info license:GPL-3.0 \
			--info depends:\"jsonfilter curl\" \
			--files \"\$STAGING_DIR\" \
			--output \"release-assets/${PKG_NAME}-${VERSION}-r${RELEASE}.apk\"

		rm -rf \"\$STAGING_DIR\"
	"
else
	echo "==> Docker not found, generating APK package via tarstream..."
	STAGING_DIR=$(mktemp -d)
	mkdir -p "$STAGING_DIR/etc/config" "$STAGING_DIR/etc/init.d" "$STAGING_DIR/etc/uci-defaults"
	mkdir -p "$STAGING_DIR/usr/libexec/rpcd" "$STAGING_DIR/usr/share/luci/menu.d" "$STAGING_DIR/usr/share/rpcd/acl.d"
	mkdir -p "$STAGING_DIR/usr/share/softethermg" "$STAGING_DIR/www/luci-static/resources/view/softethermg"

	cp -r root/etc/* "$STAGING_DIR/etc/"
	cp -r root/usr/* "$STAGING_DIR/usr/"
	cp -r htdocs/luci-static/resources/view/softethermg/* "$STAGING_DIR/www/luci-static/resources/view/softethermg/"

	chmod +x "$STAGING_DIR/etc/init.d/softethermg"
	chmod +x "$STAGING_DIR/usr/share/softethermg/api.sh"
	chmod +x "$STAGING_DIR/usr/libexec/rpcd/luci.softethermg"

	cat << EOF_PKG > "$STAGING_DIR/.PKGINFO"
# Generated by luci-app-softethermg builder
pkgname = ${PKG_NAME}
pkgver = ${VERSION}-r${RELEASE}
pkgdesc = LuCI support for SoftEther VPN Server Manager
url = https://github.com/siryle/luci-app-softethermg
builddate = $(date +%s)
packager = Sean <siryle1213@gmail.com>
size = 204800
arch = all
license = GPL-3.0
origin = ${PKG_NAME}
depend = jsonfilter curl
EOF_PKG

	(cd "$STAGING_DIR" && tar -czf "$DIST_DIR/${PKG_NAME}-${VERSION}-r${RELEASE}.apk" ./*)
	rm -rf "$STAGING_DIR"
fi

# 2. Build legacy OPKG IPK package
echo "==> Building legacy IPK package..."
STAGING_DIR=$(mktemp -d)
IPK_DIR=$(mktemp -d)
mkdir -p "$STAGING_DIR/etc/config" "$STAGING_DIR/etc/init.d" "$STAGING_DIR/etc/uci-defaults"
mkdir -p "$STAGING_DIR/usr/libexec/rpcd" "$STAGING_DIR/usr/share/luci/menu.d" "$STAGING_DIR/usr/share/rpcd/acl.d"
mkdir -p "$STAGING_DIR/usr/share/softethermg" "$STAGING_DIR/www/luci-static/resources/view/softethermg"

cp -r root/etc/* "$STAGING_DIR/etc/"
cp -r root/usr/* "$STAGING_DIR/usr/"
cp -r htdocs/luci-static/resources/view/softethermg/* "$STAGING_DIR/www/luci-static/resources/view/softethermg/"

chmod +x "$STAGING_DIR/etc/init.d/softethermg"
chmod +x "$STAGING_DIR/usr/share/softethermg/api.sh"
chmod +x "$STAGING_DIR/usr/libexec/rpcd/luci.softethermg"

echo "2.0" > "$IPK_DIR/debian-binary"
mkdir -p "$IPK_DIR/control"
cat << EOF_CTRL > "$IPK_DIR/control/control"
Package: ${PKG_NAME}
Version: ${VERSION}-${RELEASE}
Depends: jsonfilter, curl
Section: luci
Architecture: all
Maintainer: Sean <siryle1213@gmail.com>
Description: LuCI support for SoftEther VPN Server Manager
EOF_CTRL
echo "/etc/config/softethermg" > "$IPK_DIR/control/conffiles"

(cd "$IPK_DIR/control" && tar -czf "$IPK_DIR/control.tar.gz" ./*)
(cd "$STAGING_DIR" && tar -czf "$IPK_DIR/data.tar.gz" ./*)
(cd "$IPK_DIR" && tar -czf "$DIST_DIR/${PKG_NAME}_${VERSION}-${RELEASE}_all.ipk" debian-binary control.tar.gz data.tar.gz)

rm -rf "$STAGING_DIR" "$IPK_DIR"
echo "==> Package build completed: $(ls "$DIST_DIR")"
